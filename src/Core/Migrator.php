final class Migrator {

	public static function maybe_upgrade(): void {
		if ( get_option( 'logierp_db_version' ) === LOGIERP_DB_VERSION ) {
			return;
		}
		try {
			self::migrate();
		} catch ( \Throwable $e ) {
			\LogiERP\Support\Logger::error( 'Migration échouée : ' . $e->getMessage() );
			add_action(
				'admin_notices',
				static function (): void {
					echo '<div class="notice notice-error"><p>' . esc_html__( 'LogiERP : la mise à jour de la base de données a échoué. Les données sont intactes. Consultez Outils LogiERP › Santé.', 'logierp' ) . '</p></div>';
				}
			);
		}
	}

	public static function migrate(): void {
		global $wpdb;
		require_once ABSPATH . 'wp-admin/includes/upgrade.php';
		$c = $wpdb->get_charset_collate();
		foreach ( self::schema() as $table => $body ) {
			$name = Db::t( $table );
			dbDelta( "CREATE TABLE {$name} (\n{$body}\n) ENGINE=InnoDB {$c};" );
		}
		$prev = (string) get_option( 'logierp_db_version', '' );
		if ( '' !== $prev && version_compare( $prev, '1.4.0', '<' ) ) {
			// 1.4.0 : codes de transaction SAP ; le scénario FEFO garde le repérage manuel des lots périmés.
			Tcodes::migrate_data();
			$wpdb->update( Db::t( 'scenario' ), array( 'expiry_mode' => 'MANUEL' ), array( 'template_key' => 'cold_fefo' ) );
		}
		if ( '' !== $prev && version_compare( $prev, '1.7.0', '<' ) ) {
			// 1.7.0 : chaque article porte un EAN-13 valide et unique (étiquettes scannables).
			self::ensure_ean13();
		}
		// 2.0.0 : le segment de stock inclut le stock spécial (stock client E) ; l'ancienne clé est retirée.
		$st = Db::t( 'stock' );
		if ( $wpdb->get_var( $wpdb->prepare( "SHOW INDEX FROM {$st} WHERE Key_name = %s", 'stock_key' ) ) ) { // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
			$wpdb->query( "ALTER TABLE {$st} DROP INDEX stock_key" ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared,WordPress.DB.DirectDatabaseQuery.SchemaChange
		}
		if ( '' !== $prev && version_compare( $prev, '2.0.0', '<' ) ) {
			// 2.0.0 : citernes (310) et aire des écarts (999) ; les données de procédé suivent par la révision 6 du jeu de données.
			\LogiERP\Seeder\WarehouseBuilder::build();
			// Le bord de ligne reçoit aussi les emballages et matières de la chimie de procédé (magasins de production).
			$wpdb->query( $wpdb->prepare( 'UPDATE ' . Db::t( 'storage_location' ) . " SET profiles = %s, adr_classes = %s WHERE code = '500' AND profiles = 'STD,SMALL,PAL'", 'STD,SMALL,PAL,CHEM,BULKY', '3,8,5.1' ) ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
			\LogiERP\Domain\Catalog::reset_cache();
		}
		update_option( 'logierp_db_version', LOGIERP_DB_VERSION, true );
	}

	/** Attribue un EAN-13 interne aux articles sans code valide (ou en double dans leur jeu de données). */
	public static function ensure_ean13(): int {
		global $wpdb;
		$t    = Db::t( 'material' );
		$rows = (array) $wpdb->get_results( "SELECT id, dataset_id, material_no, ean FROM {$t} ORDER BY id", ARRAY_A ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$seen = array();
		$n    = 0;
		foreach ( $rows as $r ) {
			$k = $r['dataset_id'] . ':' . $r['ean'];
			if ( \LogiERP\Domain\Gs1::is_ean13( (string) $r['ean'] ) && ! isset( $seen[ $k ] ) ) {
				$seen[ $k ] = true;
				continue;
			}
			$ean = \LogiERP\Domain\Gs1::internal_ean13( (string) $r['material_no'], (int) $r['dataset_id'], (int) $r['id'] );
			$wpdb->update( $t, array( 'ean' => $ean ), array( 'id' => (int) $r['id'] ) );
			$seen[ $r['dataset_id'] . ':' . $ean ] = true;
			++$n;
		}
		return $n;
	}

